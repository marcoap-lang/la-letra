import { initializeTestEnvironment, assertSucceeds, assertFails } from "@firebase/rules-unit-testing";
import { readFileSync } from "node:fs";
import { doc, getDoc, setDoc, deleteDoc } from "firebase/firestore";
const env = await initializeTestEnvironment({ projectId: "demo-la-letra", firestore: { rules: readFileSync("/workspace/la-letra/firestore.rules", "utf8"), host: "127.0.0.1", port: 8085 } });
const snap = { version: 2, jobs: [] };
const body = (rev, email = "marcoap@gmail.com") => ({ revision: rev, updatedAt: new Date(), updatedBy: email, snapshot: snap });
const me = env.authenticatedContext("u1", { email: "marcoap@gmail.com", email_verified: true }).firestore();
const meUnverified = env.authenticatedContext("u1", { email: "marcoap@gmail.com", email_verified: false }).firestore();
const other = env.authenticatedContext("u2", { email: "otro@gmail.com", email_verified: true }).firestore();
const papa = env.authenticatedContext("u3", { email: "imprentalaletra2@gmail.com", email_verified: true }).firestore();
const papaUnv = env.authenticatedContext("u3", { email: "imprentalaletra2@gmail.com", email_verified: false }).firestore();
const anon = env.unauthenticatedContext().firestore();
const R = (db, p = "shops/la-letra") => doc(db, p);
const results = [];
async function t(name, p) { try { await p; results.push("PASS " + name); } catch (e) { results.push("FAIL " + name + " :: " + e.message.slice(0,80)); } }
await t("anon read denied", assertFails(getDoc(R(anon))));
await t("anon write denied", assertFails(setDoc(R(anon), body(1))));
await t("other user read denied", assertFails(getDoc(R(other))));
await t("other user write denied", assertFails(setDoc(R(other), body(1, "otro@gmail.com"))));
await t("unverified read denied", assertFails(getDoc(R(meUnverified))));
await t("unverified write denied", assertFails(setDoc(R(meUnverified), body(1))));
await t("allowed create rev 2 denied", assertFails(setDoc(R(me), body(2))));
await t("allowed create rev 1 ok", assertSucceeds(setDoc(R(me), body(1))));
await t("allowed read ok", assertSucceeds(getDoc(R(me))));
await t("update same rev denied", assertFails(setDoc(R(me), body(1))));
await t("update skip rev denied", assertFails(setDoc(R(me), body(3))));
await t("update rev 2 ok", assertSucceeds(setDoc(R(me), body(2))));
await t("stale update (rev 2 again) denied", assertFails(setDoc(R(me), body(2))));
await t("spoofed updatedBy denied", assertFails(setDoc(R(me), body(3, "x@y.com"))));
await t("extra field denied", assertFails(setDoc(R(me), { ...body(3), extra: 1 })));
await t("snapshot not map denied", assertFails(setDoc(R(me), { ...body(3), snapshot: "x" })));
await t("papa read ok", assertSucceeds(getDoc(R(papa))));
await t("papa unverified read denied", assertFails(getDoc(R(papaUnv))));
await t("papa update rev 3 ok", assertSucceeds(setDoc(R(papa), body(3, "imprentalaletra2@gmail.com"))));
await t("delete denied", assertFails(deleteDoc(R(me))));
await t("other doc read denied", assertFails(getDoc(R(me, "shops/otra"))));
await t("other collection write denied", assertFails(setDoc(R(me, "x/y"), { a: 1 })));
console.log(results.join("\n"));
await env.cleanup();
